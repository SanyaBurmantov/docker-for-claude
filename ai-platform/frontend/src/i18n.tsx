const dictionaries: Record<Language, Dictionary> = { ru, en }
const STORAGE_KEY = 'interface-language'

interface LanguageContextValue {
  language: Language
  locale: string
  setLanguage: (language: Language) => void
  t: (key: string, variables?: Variables) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() =>
    localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : 'ru'
  )

  const setLanguage = useCallback((next: Language) => {
    localStorage.setItem(STORAGE_KEY, next)
    setLanguageState(next)
  }, [])

  const t = useCallback((key: string, variables: Variables = {}) => {
    const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key
    return template.replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`))
  }, [language])

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  useEffect(() => {
    const syncFromAnotherWindow = (event: StorageEvent) => {
      if (event.key === STORAGE_KEY && (event.newValue === 'ru' || event.newValue === 'en')) {
        setLanguageState(event.newValue)
      }
    }
    window.addEventListener('storage', syncFromAnotherWindow)
    return () => window.removeEventListener('storage', syncFromAnotherWindow)
  }, [])

  const value = useMemo(() => ({
    language,
    locale: language === 'ru' ? 'ru-RU' : 'en-US',
    setLanguage,
    t,
  }), [language, setLanguage, t])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage(): LanguageContextValue {
  const value = useContext(LanguageContext)
  if (!value) throw new Error('useLanguage must be used inside LanguageProvider')
  return value
}
